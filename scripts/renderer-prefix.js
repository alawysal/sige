function pruneActions(){
 host.querySelectorAll('.chip-opt').forEach(el=>{el.setAttribute('role','checkbox');el.tabIndex=0;el.setAttribute('aria-checked',String(el.classList.contains('on')));});
 const alive=new Set();host.querySelectorAll('[data-sige-click],[data-sige-input],[data-sige-change]').forEach(el=>{for(const type of ['click','input','change']){const key=el.getAttribute('data-sige-'+type);if(key)alive.add(key);}});
 for(const key of actions.keys())if(!alive.has(key))actions.delete(key);
}
