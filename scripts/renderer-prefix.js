async function runAction(fn){
 if(actionRunning||destroyed)return;
 const before=structuredClone(DB);
 const refs=Object.fromEntries(Object.entries(DB).filter(([,value])=>Array.isArray(value)).map(([key,value])=>[key,value.slice()]));
 actionRunning=true;dirty=false;externalCommit=false;effects=[];needsRender=false;bridge.busy(true);
 try{
  await fn();
  if(dirty&&!externalCommit)DB=await bridge.commit(before,DB);
  const pending=effects;effects=[];actionRunning=false;bridge.changed(DB);
  for(const effect of pending)effect();
  if(dirty||needsRender)renderView();
 }catch(error){
  // Restore record objects in place so an open form can be corrected and submitted again.
  for(const [key,items] of Object.entries(refs)){
   for(let i=0;i<items.length;i++){const item=items[i];if(item&&typeof item==='object'){for(const field of Object.keys(item))delete item[field];Object.assign(item,structuredClone(before[key][i]));}}
   before[key]=items;
  }
  DB=before;actionRunning=false;effects=[];
  toast(bridge.error(error),'err');
 }finally{actionRunning=false;bridge.busy(false);queueMicrotask(pruneActions);}
}
const handlers={};
for(const type of ['click','input','change']){
 handlers[type]=event=>{
  // A click inside a modal must keep native input, label and file-picker behaviour.
  if(type==='click'&&event.target.matches('input[type="date"]:not(:disabled):not([readonly])')){
   try{event.target.showPicker?.();}catch{/* Browsers without picker support retain native keyboard input. */}
  }
  const element=event.target.closest('[data-sige-'+type+']');if(!element||!host.contains(element))return;
  if(type==='click'&&element.classList.contains('modal')&&event.target!==element)return;
  const fn=actions.get(element.getAttribute('data-sige-'+type));if(fn){if(type==='click')event.preventDefault();runAction(()=>fn(event,element));}
 };
 host.addEventListener(type,handlers[type]);
}
